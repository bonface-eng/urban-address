export async function seedCarWashServices(supabaseClient) {
  const { data, error } = await supabaseClient
    .from('carwash_services')
    .upsert(CAR_WASH_SERVICE_SEEDS, { onConflict: 'id', ignoreDuplicates: true })
    .select('id');

  if (error) throw error;
  return { inserted: data?.length ?? 0, totalSeedDefinitions: CAR_WASH_SERVICE_SEEDS.length };
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith('seed-carwash-services.mjs')) {
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !serviceKey) {
    console.error('Missing NEXT_PUBLIC_SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY');
    process.exit(1);
  }
  const client = createClient(url, serviceKey, { auth: { persistSession: false } });
  seedCarWashServices(client)
    .then((res) => {
      console.log(`Carwash services seed complete. Newly inserted: ${res.inserted} (definitions: ${res.totalSeedDefinitions}).`);
    })
    .catch((err) => {
      console.error('Failed to seed carwash services:', err);
      process.exit(1);
    });
}
